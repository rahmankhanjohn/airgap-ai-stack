// Package report renders the accreditation document: bundle contents,
// egress attestation, eval results, and host identity in one markdown file.
package report

import (
	"fmt"
	"strings"
	"time"

	"github.com/rahmankhanjohn/airgap-ai-stack/internal/bundle"
	"github.com/rahmankhanjohn/airgap-ai-stack/internal/egress"
	"github.com/rahmankhanjohn/airgap-ai-stack/internal/eval"
)

// Input carries everything the report needs; nil sections are skipped.
type Input struct {
	Bundle    *bundle.Manifest
	BundleDir string
	Problems  []string
	Egress    *egress.Summary
	Eval      *eval.Report
	Host      string // os/arch string
	Notes     string
}

// Markdown renders the accreditation report.
func Markdown(in Input) string {
	var b strings.Builder
	b.WriteString("# Air-Gap Accreditation Report\n\n")
	fmt.Fprintf(&b, "Generated: %s\n\n", time.Now().UTC().Format(time.RFC3339))

	if in.Host != "" {
		b.WriteString("## Host\n\n")
		fmt.Fprintf(&b, "- Platform: %s\n", in.Host)
		b.WriteString("\n")
	}

	if in.Bundle != nil {
		b.WriteString("## Bundle\n\n")
		fmt.Fprintf(&b, "- Name: %s\n", in.Bundle.Name)
		fmt.Fprintf(&b, "- Format version: %s\n", in.Bundle.FormatVersion)
		fmt.Fprintf(&b, "- Created: %s\n", in.Bundle.Created.Format(time.RFC3339))
		fmt.Fprintf(&b, "- Runtime: %s\n", in.Bundle.Runtime.Binary)
		if in.BundleDir != "" {
			fmt.Fprintf(&b, "- Path: %s\n", in.BundleDir)
		}
		b.WriteString("\n### Files\n\n")
		b.WriteString("| Path | Role | Bytes | SHA256 (first 16) |\n|---|---|---:|---|\n")
		for _, f := range in.Bundle.Files {
			short := f.SHA256
			if len(short) > 16 {
				short = short[:16] + "..."
			}
			fmt.Fprintf(&b, "| %s | %s | %d | %s |\n", f.Path, f.Role, f.Bytes, short)
		}
		b.WriteString("\n")
		if len(in.Problems) > 0 {
			b.WriteString("### Verification problems\n\n")
			for _, p := range in.Problems {
				fmt.Fprintf(&b, "- %s\n", p)
			}
			b.WriteString("\n")
		} else {
			b.WriteString("Verification: all files present, all hashes match.\n\n")
		}
	}

	if in.Egress != nil {
		b.WriteString("## Egress attestation\n\n")
		verdict := "FAILED"
		if in.Egress.AirGap {
			verdict = "PASS"
		}
		fmt.Fprintf(&b, "Verdict: **%s** - %s\n\n", verdict, in.Egress.Verdict)
		b.WriteString("| Probe | Target | Reachable | Detail |\n|---|---|---|---|\n")
		for _, p := range in.Egress.Probes {
			detail := p.Error
			if detail == "" {
				detail = p.Latency
			}
			fmt.Fprintf(&b, "| %s | %s | %t | %s |\n", p.Probe, p.Target, p.OK, detail)
		}
		b.WriteString("\n")
	}

	if in.Eval != nil {
		b.WriteString("## Evaluation\n\n")
		fmt.Fprintf(&b, "- Suite: %s\n", in.Eval.Suite)
		fmt.Fprintf(&b, "- Endpoint: %s\n", in.Eval.Endpoint)
		if in.Eval.Model != "" {
			fmt.Fprintf(&b, "- Model: %s\n", in.Eval.Model)
		}
		fmt.Fprintf(&b, "- Score: %d/%d (%.0f%%)\n\n", in.Eval.Passed, in.Eval.Total, in.Eval.Score*100)
		b.WriteString("| Case | Verdict | Duration | Detail |\n|---|---|---|---|\n")
		for _, r := range in.Eval.Results {
			verdict := "PASS"
			detail := ""
			if !r.Passed {
				verdict = "FAIL"
				detail = strings.Join(r.Failures, "; ")
			}
			if r.Error != "" {
				detail = r.Error
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", r.ID, verdict, r.Duration, detail)
		}
		b.WriteString("\n")
	}

	if in.Notes != "" {
		b.WriteString("## Notes\n\n")
		b.WriteString(in.Notes)
		b.WriteString("\n")
	}

	b.WriteString("\n---\n\nGenerated by airgap (github.com/rahmankhanjohn/airgap-ai-stack). ")
	b.WriteString("Attestation scope: probes listed above only. See SECURITY.md.\n")
	return b.String()
}
